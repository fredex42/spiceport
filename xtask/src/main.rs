//! Project automation: `cargo xtask <command>`.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, bail};

mod dist;

fn main() -> anyhow::Result<()> {
    let cmd = std::env::args().nth(1);
    match cmd.as_deref() {
        Some("gen-keymap") => gen_keymap(),
        Some("dist") => dist::dist(std::env::args().skip(2).collect()),
        _ => {
            eprintln!(
                "usage: cargo xtask <command>\n\ncommands:\n  gen-keymap   regenerate spiceport/src/keymap_generated.rs from keycodemapdb\n  dist [--target T] [--no-build]\n               build a release and package it into target/dist"
            );
            std::process::exit(2);
        }
    }
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .to_path_buf()
}

fn parse_num(s: &str) -> Option<u32> {
    if s.is_empty() {
        None
    } else if let Some(h) = s.strip_prefix("0x") {
        u32::from_str_radix(h, 16).ok()
    } else {
        s.parse().ok()
    }
}

/// USB HID usage (what SDL scancodes are) → "xtkbd", the encoding SPICE's
/// inputs channel takes: AT set 1, with 0xe0-prefixed codes folded into 0x100|code.
/// Mirrors `keymap-gen code-map keymaps.csv usb xtkbd` as run by spice-gtk's meson.build.
fn gen_keymap() -> anyhow::Result<()> {
    let csv = root().join("spice-gtk/subprojects/keycodemapdb/data/keymaps.csv");
    let text = fs::read_to_string(&csv).with_context(|| {
        format!(
            "reading {} (run `git submodule update --init --recursive`)",
            csv.display()
        )
    })?;
    let mut lines = text.lines();
    let header: Vec<&str> = lines.next().context("empty csv")?.split(',').collect();
    let col = |name: &str| {
        header
            .iter()
            .position(|h| h.trim_matches('"') == name)
            .with_context(|| format!("column {name} missing"))
    };
    let (c_name, c_at1, c_usb) = (
        col("Linux Name")?,
        col("AT set1 keycode")?,
        col("USB Keycodes")?,
    );

    // keymap-gen keeps the *last* row for a duplicated source code; do the same.
    let mut map: BTreeMap<u32, (u32, String)> = BTreeMap::new();
    for line in lines {
        let row: Vec<&str> = line.split(',').collect();
        let (Some(usb), Some(at1)) = (
            row.get(c_usb).and_then(|s| parse_num(s)),
            row.get(c_at1).and_then(|s| parse_num(s)),
        ) else {
            continue;
        };
        let xt = if at1 > 0x7f {
            if at1 & !0x7f != 0xe000 {
                bail!("unexpected AT set1 code {at1:#x}");
            }
            0x100 | (at1 & 0x7f)
        } else {
            at1
        };
        map.insert(usb, (xt, row[c_name].to_string()));
    }
    let len = map.keys().max().map_or(0, |m| m + 1);

    let mut out = String::from(
        "// @generated by `cargo xtask gen-keymap` from\n\
         // spice-gtk/subprojects/keycodemapdb/data/keymaps.csv (BSD-3-Clause).\n\
         // Do not edit by hand.\n\n\
         /// USB HID usage (= SDL scancode) → XT set 1 scancode as SPICE expects it:\n\
         /// codes with an 0xe0 prefix have the prefix dropped and 0x100 set. 0 = unmapped.\n",
    );
    out += &format!("pub static USB_TO_XTKBD: [u16; {len}] = [\n");
    for usb in 0..len {
        match map.get(&usb) {
            Some((xt, name)) if *xt != 0 => {
                out += &format!("    {xt:#06x}, // {usb:#04x} {name}\n")
            }
            _ => out += &format!("    0, // {usb:#04x}\n"),
        }
    }
    out += "];\n";
    let dest = root().join("spiceport/src/keymap_generated.rs");
    fs::write(&dest, out)?;
    println!("wrote {} ({} entries)", dest.display(), map.len());
    Ok(())
}
